import io
from datetime import datetime
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

def generate_activity_excel(project, date_str, activities, manager_name="Project Manager", start_date=None, end_date=None):
    """
    Generates a beautifully styled .xlsx Excel file containing activities
    (single day or date range like weekly/monthly) for all team members in the given project.
    """
    wb = openpyxl.Workbook()
    ws = wb.active
    
    clean_title_date = (start_date if start_date == end_date else f"{start_date}_to_{end_date}") if (start_date and end_date) else date_str
    ws.title = f"Activity_{clean_title_date}"[:31].replace(":", "-").replace("/", "-")
    ws.views.sheetView[0].showGridLines = True

    # ---------------- Color Palette & Styles ----------------
    font_family = "Segoe UI"
    
    # Fonts
    title_font = Font(name=font_family, size=15, bold=True, color="1E1B4B")
    subtitle_font = Font(name=font_family, size=10, bold=False, color="475569")
    meta_bold_font = Font(name=font_family, size=10, bold=True, color="1E293B")
    kpi_number_font = Font(name=font_family, size=15, bold=True, color="4338CA")
    table_header_font = Font(name=font_family, size=10, bold=True, color="FFFFFF")
    data_font = Font(name=font_family, size=9.5, color="1E293B")
    data_bold_font = Font(name=font_family, size=9.5, bold=True, color="1E293B")
    time_font = Font(name=font_family, size=9, color="64748B")
    date_col_font = Font(name=font_family, size=9, bold=True, color="334155")
    
    # Fills
    primary_header_fill = PatternFill(start_color="4F46E5", end_color="4F46E5", fill_type="solid") # Indigo 600
    banner_fill = PatternFill(start_color="EEF2FF", end_color="EEF2FF", fill_type="solid") # Indigo 50
    kpi_card_fill = PatternFill(start_color="F8FAFC", end_color="F8FAFC", fill_type="solid") # Slate 50
    row_alt_fill = PatternFill(start_color="F8FAFC", end_color="F8FAFC", fill_type="solid") # Slate 50
    white_fill = PatternFill(start_color="FFFFFF", end_color="FFFFFF", fill_type="solid")
    
    # Status Stage Fills & Fonts
    stage_styles = {
        "todo": {"fill": PatternFill(start_color="F1F5F9", end_color="F1F5F9", fill_type="solid"), "font": Font(name=font_family, size=9, color="475569", bold=True)},
        "in_progress": {"fill": PatternFill(start_color="E0F2FE", end_color="E0F2FE", fill_type="solid"), "font": Font(name=font_family, size=9, color="0369A1", bold=True)},
        "review": {"fill": PatternFill(start_color="FEF3C7", end_color="FEF3C7", fill_type="solid"), "font": Font(name=font_family, size=9, color="B45309", bold=True)},
        "done": {"fill": PatternFill(start_color="DCFCE7", end_color="DCFCE7", fill_type="solid"), "font": Font(name=font_family, size=9, color="15803D", bold=True)},
    }
    
    # Borders
    thin_border_side = Side(style="thin", color="CBD5E1")
    cell_border = Border(left=thin_border_side, right=thin_border_side, top=thin_border_side, bottom=thin_border_side)
    thick_bottom_side = Side(style="medium", color="4338CA")
    header_border = Border(left=thin_border_side, right=thin_border_side, top=thin_border_side, bottom=thick_bottom_side)
    card_border = Border(left=thin_border_side, right=thin_border_side, top=thin_border_side, bottom=thin_border_side)

    # Alignments
    align_center = Alignment(horizontal="center", vertical="center")
    align_left = Alignment(horizontal="left", vertical="center")
    align_wrap_left = Alignment(horizontal="left", vertical="center", wrap_text=True)

    # ---------------- 1. Title Banner ----------------
    ws.merge_cells("A1:J1")
    title_cell = ws["A1"]
    title_cell.value = "TaskFlow • Project Team Activity Audit Report"
    title_cell.font = title_font
    title_cell.fill = banner_fill
    title_cell.alignment = Alignment(horizontal="left", vertical="center", indent=1)
    ws.row_dimensions[1].height = 36

    # Project Metadata
    proj_title = project.get("title", "Project")
    proj_key = project.get("key", "PRJ")
    
    ws["A2"] = "Project:"
    ws["A2"].font = meta_bold_font
    ws["B2"] = f"{proj_title} ({proj_key})"
    ws["B2"].font = data_bold_font

    ws["D2"] = "Date / Period:"
    ws["D2"].font = meta_bold_font
    ws["E2"] = date_str
    ws["E2"].font = data_bold_font

    ws["H2"] = "Generated By:"
    ws["H2"].font = meta_bold_font
    ws["I2"] = manager_name
    ws["I2"].font = data_bold_font

    ws.row_dimensions[2].height = 20

    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    ws["A3"] = "Generated At:"
    ws["A3"].font = subtitle_font
    ws["B3"] = now_str
    ws["B3"].font = subtitle_font
    ws.row_dimensions[3].height = 18

    # ---------------- 2. Summary KPI Cards ----------------
    total_acts = len(activities)
    stage_moves = sum(1 for a in activities if a.get("action") in ["status_changed", "status_change"])
    tasks_created = sum(1 for a in activities if a.get("action") in ["created", "task_created"])
    comments_added = sum(1 for a in activities if a.get("action") in ["comment_added"])
    unique_users = len(set(a.get("user") for a in activities if a.get("user")))

    # KPI Row 5 (Span across A to J)
    kpis = [
        ("A5", "B5", "TOTAL ACTIVITIES", str(total_acts)),
        ("C5", "D5", "STAGE TRANSITIONS", str(stage_moves)),
        ("E5", "F5", "TASKS CREATED", str(tasks_created)),
        ("G5", "H5", "COMMENTS POSTED", str(comments_added)),
        ("I5", "J5", "ACTIVE CONTRIBUTORS", str(unique_users)),
    ]

    ws.row_dimensions[4].height = 8 # Spacer
    ws.row_dimensions[5].height = 32

    for start_col, end_col, label, val in kpis:
        if start_col != end_col:
            ws.merge_cells(f"{start_col}:{end_col}")
        cell = ws[start_col]
        cell.value = f"{val}\n{label}"
        cell.font = kpi_number_font
        cell.fill = kpi_card_fill
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        col_letters = [start_col[0]] if start_col == end_col else [start_col[0], end_col[0]]
        for col_l in col_letters:
            ws[f"{col_l}5"].border = card_border

    ws.row_dimensions[6].height = 10 # Spacer

    # ---------------- 3. Table Headers ----------------
    headers = [
        ("#", 6, align_center),
        ("Date", 13, align_center),
        ("Time", 13, align_center),
        ("Team Member / User", 22, align_left),
        ("Action Type", 17, align_center),
        ("Task ID", 13, align_center),
        ("Task Title", 30, align_left),
        ("From Stage", 15, align_center),
        ("To Stage", 15, align_center),
        ("Activity Description & Details", 50, align_left)
    ]

    header_row = 7
    ws.row_dimensions[header_row].height = 26

    for col_idx, (col_name, col_width, alignment) in enumerate(headers, start=1):
        cell = ws.cell(row=header_row, column=col_idx)
        cell.value = col_name
        cell.font = table_header_font
        cell.fill = primary_header_fill
        cell.alignment = alignment
        cell.border = header_border
        col_letter = get_column_letter(col_idx)
        ws.column_dimensions[col_letter].width = col_width

    # Freeze panes so header row remains fixed while scrolling
    ws.freeze_panes = "A8"

    # ---------------- 4. Activity Rows ----------------
    current_row = 8
    if not activities:
        ws.merge_cells(f"A{current_row}:J{current_row}")
        empty_cell = ws[f"A{current_row}"]
        empty_cell.value = f"No activities recorded for {date_str} in this project."
        empty_cell.font = Font(name=font_family, size=10, italic=True, color="64748B")
        empty_cell.alignment = align_center
        empty_cell.fill = white_fill
        ws.row_dimensions[current_row].height = 30
        for col_i in range(1, 11):
            ws.cell(row=current_row, column=col_i).border = cell_border
        current_row += 1
    else:
        for idx, act in enumerate(activities, start=1):
            ws.row_dimensions[current_row].height = 24
            row_fill = row_alt_fill if idx % 2 == 0 else white_fill

            # Format Date and Time
            ts = act.get("timestamp", "")
            time_str = ""
            date_col_str = act.get("date") or (ts[:10] if len(ts) >= 10 else "")
            if ts:
                try:
                    dt_clean = ts.replace("Z", "+00:00")
                    dt = datetime.fromisoformat(dt_clean)
                    time_str = dt.strftime("%I:%M:%S %p")
                    date_col_str = dt.strftime("%Y-%m-%d")
                except Exception:
                    time_str = ts[11:19] if len(ts) >= 19 else ts
            
            # Action Label
            raw_action = (act.get("action") or "").lower()
            if "status" in raw_action:
                action_display = "Moved Stage"
            elif "create" in raw_action:
                action_display = "Task Created"
            elif "comment" in raw_action:
                action_display = "Comment Added"
            elif "priority" in raw_action:
                action_display = "Priority Changed"
            elif "assign" in raw_action:
                action_display = "Assignee Changed"
            elif "delete" in raw_action:
                action_display = "Task Deleted"
            else:
                action_display = raw_action.replace("_", " ").title()

            from_st = act.get("fromStatus") or "-"
            to_st = act.get("toStatus") or "-"

            def clean_stage_name(st):
                if not st or st == "-": return "-"
                s = st.lower().replace(" ", "_")
                if "progress" in s: return "In Progress"
                if "review" in s: return "Review"
                if "done" in s: return "Done"
                if "todo" in s or "to_do" in s: return "To Do"
                return st.title()

            from_display = clean_stage_name(from_st)
            to_display = clean_stage_name(to_st)

            row_values = [
                (idx, align_center, data_font, None),
                (date_col_str, align_center, date_col_font, None),
                (time_str, align_center, time_font, None),
                (act.get("user") or "Unknown", align_left, data_bold_font, None),
                (action_display, align_center, data_bold_font, None),
                (act.get("taskKey") or "-", align_center, data_bold_font, None),
                (act.get("taskTitle") or "-", align_left, data_font, None),
                (from_display, align_center, data_font, from_st),
                (to_display, align_center, data_font, to_st),
                (act.get("details") or "-", align_wrap_left, data_font, None),
            ]

            for c_idx, (val, alignment, font, stage_key) in enumerate(row_values, start=1):
                cell = ws.cell(row=current_row, column=c_idx)
                cell.value = val
                cell.font = font
                cell.alignment = alignment
                cell.border = cell_border
                
                st_norm = str(stage_key).lower().replace(" ", "_") if stage_key else ""
                if st_norm in stage_styles:
                    cell.fill = stage_styles[st_norm]["fill"]
                    cell.font = stage_styles[st_norm]["font"]
                else:
                    cell.fill = row_fill

            current_row += 1

    # ---------------- 5. Footer / Notes ----------------
    current_row += 1
    ws.merge_cells(f"A{current_row}:J{current_row}")
    footer_cell = ws[f"A{current_row}"]
    footer_cell.value = f"Confidential • Generated by TaskFlow Project Management Suite • {now_str}"
    footer_cell.font = Font(name=font_family, size=8, italic=True, color="94A3B8")
    footer_cell.alignment = align_center

    output = io.BytesIO()
    wb.save(output)
    output.seek(0)
    return output.getvalue()
